// Embed a compiled kernel as src/kernel/kernel.wasm.ts (base64), so the site ships one script
// and works where .wasm files cannot be served. Usage: node scripts/embed-wasm.mjs <file.wasm>
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const [wasm] = process.argv.slice(2);
if (!wasm) throw new Error('usage: node scripts/embed-wasm.mjs <file.wasm>');
const bytes = readFileSync(wasm);
if (bytes.readUInt32LE(0) !== 0x6d736100) throw new Error(`${wasm} is not a WebAssembly module`);
const out = fileURLToPath(new URL('../src/kernel/kernel.wasm.ts', import.meta.url));
writeFileSync(out, `// Generated by scripts/embed-wasm.mjs from rust/. Do not edit.\nexport const KERNEL_WASM = "${bytes.toString('base64')}";\n`);
console.log(`embedded ${bytes.length} bytes`);
